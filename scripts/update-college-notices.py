"""Refresh recent public college notices from the official source registry."""

import argparse
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass, field
from datetime import date, datetime, timedelta, timezone
from html.parser import HTMLParser
import json
from pathlib import Path
import re
from urllib.error import HTTPError
from urllib.parse import urljoin, urlsplit, urlunsplit
from urllib.request import HTTPRedirectHandler, Request, build_opener
from urllib.robotparser import RobotFileParser

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / 'scripts' / 'college-sources.json'
OUTPUT = ROOT / 'web' / 'college-bulletins.js'
HEADER = '// Generated by scripts/update-college-notices.py.\nexport const collegeBulletins = '
AGENT = 'PathFinderNoticeReader/1.0'
TODAY = datetime.now(timezone(timedelta(hours=8))).date()
NOTICE = re.compile('通知|公告|公示|招募|招生简章|招生办法|招生计划|申请指南|报名|实施细则|选课|录取|推免')
UNRELATED = re.compile('党委|职务任免|任职的通知|预备党员|推优入党|组织关系')
SECTION = re.compile('^(?:面向学生的?|本科生?|研究生|学生工作|教务|学院)?(?:通知(?:公告|通告|指南)?|公告|通告|招生信息|通知公告和下载)$')
DATE = re.compile(r'(?<![0-9])(20[0-9]{2})\s*[-./年]\s*([0-9]{1,2})\s*[-./月]\s*([0-9]{1,2})(?![0-9])')
SPLIT_DATE = re.compile(r'(?<![0-9])([0-9]{1,2})\s*(20[0-9]{2})\s*[-./年]\s*([0-9]{1,2})(?![0-9])')
YEAR_LAST = re.compile(r'(?<![0-9])([0-9]{1,2})\s*[-./]\s*([0-9]{1,2})\s*[/\s]\s*(20[0-9]{2})(?![0-9])')
HTML_LIMIT = 1_500_000


def same_host(link, home):
    a, b = urlsplit(link), urlsplit(home)
    return (a.scheme == 'https' and a.port in (None, 443) and not a.username and not a.password
            and (a.hostname or '').removeprefix('www.') == (b.hostname or '').removeprefix('www.'))


def official_link(base, href):
    if not href or href.startswith('#'):
        return None
    try:
        parts = urlsplit(urljoin(base, href))
        if parts.scheme == 'http':
            parts = parts._replace(scheme='https')
        link = urlunsplit(parts._replace(fragment=''))
        return link if same_host(link, base) else None
    except ValueError:
        return None


class OfficialRedirect(HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        if not same_host(newurl, req.full_url):
            raise ValueError('redirect outside source host')
        return super().redirect_request(req, fp, code, msg, headers, newurl)


def fetch(url):
    opener = build_opener(OfficialRedirect())
    with opener.open(Request(url, headers={'User-Agent': AGENT}), timeout=9) as response:
        body = response.read(HTML_LIMIT + 1)
        if len(body) > HTML_LIMIT:
            raise ValueError('page exceeds size limit')
        charset = response.headers.get_content_charset()
        if not charset:
            match = re.search(rb'charset\s*=\s*["\']?([\w-]+)', body[:4096], re.I)
            charset = match[1].decode('ascii') if match else 'utf-8'
        return body.decode(charset, errors='replace'), response.url


@dataclass
class Element:
    parent: object = None
    tag: str = ''
    words: list = field(default_factory=list)
    links: int = 0


class Page(HTMLParser):
    void = set('area base br col embed hr img input link meta param source track wbr'.split())

    def __init__(self, markup):
        super().__init__(convert_charrefs=True)
        self.stack = [Element()]
        self.anchors = []
        self.feed(markup)

    def handle_starttag(self, tag, attrs):
        if tag in self.void:
            return
        node = Element(self.stack[-1], tag)
        self.stack.append(node)
        if tag == 'a':
            self.anchors.append((node, dict(attrs)))
            for parent in self.stack[:-1]:
                parent.links += 1

    def handle_endtag(self, tag):
        for index in range(len(self.stack) - 1, 0, -1):
            if self.stack[index].tag == tag:
                del self.stack[index:]
                break

    def handle_data(self, data):
        if self.stack[-1].tag not in ('script', 'style'):
            text = data.strip()
            if text:
                for parent in self.stack:
                    parent.words.append(text)


def dates_in(text):
    found = set()
    for pattern, order in ((DATE, (1, 2, 3)), (SPLIT_DATE, (2, 3, 1)), (YEAR_LAST, (3, 1, 2))):
        for match in pattern.finditer(text):
            try:
                found.add(date(*(int(match[i]) for i in order)))
            except ValueError:
                continue
    return found


def card_date(anchor):
    parent = anchor
    for _ in range(5):
        if parent is None or parent.links > 3 or len(parent.words) > 30:
            return None
        context = ' '.join(parent.words)
        dates = dates_in(context)
        if len(dates) == 1:
            return dates.pop()
        if len(dates) > 1:
            return None
        parent = parent.parent


def extract(markup, url):
    records, sections = {}, []
    for anchor, attr in Page(markup).anchors:
        link = official_link(url, attr.get('href'))
        if not link or link == url:
            continue
        label = ' '.join(anchor.words).strip()
        if SECTION.fullmatch(label) and link not in sections:
            sections.append(link)
        title = clean_title(attr.get('title') or label)
        if not eligible_title(title):
            continue
        published = card_date(anchor)
        if published and TODAY - timedelta(days=365) <= published <= TODAY:
            records[link] = dict(title=title, url=link, publishedDate=published.isoformat())
    return records, sections


def clean_title(raw):
    title = re.split(r'\s{2,}|(?:近日，|日前，)', raw.strip(), maxsplit=1)[0].strip()
    for pattern in (DATE, SPLIT_DATE, YEAR_LAST):
        title = re.sub(r'^\s*' + pattern.pattern + r'\s*', '', title)
        title = re.sub(r'\s*' + pattern.pattern + r'(?:日)?\s*$', '', title)
    return re.sub(r'\s+', ' ', title).strip(' ·-/<>')


def eligible_title(title):
    return 9 <= len(title) <= 120 and NOTICE.search(title) and not UNRELATED.search(title)


def collect(entry):
    college, start = entry
    try:
        robots = RobotFileParser()
        try:
            rules, _ = fetch(urljoin(start, '/robots.txt'))
            robots.parse(rules.splitlines())
        except HTTPError as error:
            if error.code not in (404, 410):
                raise
            robots.parse([])
        if not robots.can_fetch(AGENT, start):
            return college, None, 'robots.txt'
        markup, resolved = fetch(start)
        notices, sections = extract(markup, resolved)
        source = resolved
        for section in sections[:2]:
            if not robots.can_fetch(AGENT, section):
                continue
            try:
                page, index = fetch(section)
                found, _ = extract(page, index)
                if found:
                    source = index
                    notices.update(found)
            except (OSError, ValueError):
                continue
        recent = sorted(notices.values(), key=lambda item: item['publishedDate'], reverse=True)[:8]
        return college, {'source': source, 'items': recent}, None
    except (OSError, ValueError) as error:
        return college, None, str(error)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('colleges', nargs='*', help='College IDs. The default refreshes all sources.')
    args = parser.parse_args()
    sources = json.loads(REGISTRY.read_text(encoding='utf-8'))
    unknown = set(args.colleges) - sources.keys()
    if unknown:
        parser.error('unknown college IDs: ' + ', '.join(sorted(unknown)))
    previous = json.loads(OUTPUT.read_text(encoding='utf-8').removeprefix(HEADER).strip().removesuffix(';'))
    snapshot = {}
    for key, url in sources.items():
        saved = previous.get(key, {'source': url, 'items': []})
        items = [{**item, 'title': clean_title(item['title'])} for item in saved['items']]
        snapshot[key] = {**saved, 'items': [item for item in items if eligible_title(item['title'])]}
    entries = [(key, sources[key]) for key in (args.colleges or sources)]
    with ThreadPoolExecutor(max_workers=6) as pool:
        for key, result, error in pool.map(collect, entries):
            if result and result['items']:
                snapshot[key] = {**result, 'checkedOn': TODAY.isoformat()}
            count = len(result['items']) if result else 0
            print(f'{key}: {count}' + (f' ({error})' if error else ''), flush=True)
    temporary = OUTPUT.with_suffix('.tmp')
    temporary.write_text(HEADER + json.dumps(snapshot, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
    temporary.replace(OUTPUT)


if __name__ == '__main__':
    main()
